const cache = new Map<string, Path2D>();

function pathFor(name: IconName): Path2D {
  let p = cache.get(name);
  if (!p) {
    p = new Path2D(ICON_PATHS[name]);
    cache.set(name, p);
  }
  return p;
}

/** Draw an icon into a size×size box with its top-left at (x, y). */
export function drawIcon(ctx: Ctx, name: IconName, x: number, y: number, size: number, color: string): void {
  ctx.save();
  ctx.translate(x, y);
  ctx.scale(size / 24, size / 24);
  ctx.strokeStyle = color;
  ctx.lineWidth = 1.5;
  ctx.lineCap = 'round';
  ctx.lineJoin = 'round';
  ctx.stroke(pathFor(name));
  ctx.restore();
}
